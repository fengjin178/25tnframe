export function getCharacterById(id: string): Character {
  return characters.find((c) => c.id === id) ?? characters[0];
}

export function relatedTo(id: string): CrossRelation[] {
  return crossDramaRelations.filter((r) => r.character_a === id || r.character_b === id);
}

export function otherId(rel: CrossRelation, id: string): string {
  return rel.character_a === id ? rel.character_b : rel.character_a;
}
